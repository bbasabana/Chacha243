/// Les moments marquants du 30 juin 1960 au 30 juin 2027.
///
/// Les dates suivent le document de conception ; chacune doit encore être validée par
/// des historiens avant la sortie.
enum EventKind {
  /// Médaillon à attraper : une vie.
  life,

  /// Médaillon doré : une vie, des confettis aux couleurs du drapeau.
  glory,

  /// Moment difficile : une zone d'orages à traverser.
  obstacle,

  /// Pause de recueillement, sans médaillon.
  memory,
}

class HistoryEvent {
  const HistoryEvent(
    this.year,
    this.kind,
    this.date,
    this.city,
    this.title,
    this.text, {
    this.war = false,
    this.volcano = false,
    this.photo,
    this.photo2,
    this.song,
    this.big = false,
    this.medal,
    this.intro,
    this.tag,
    this.balls = false,
  });

  /// Des ballons de football traversent le ciel : chacun apporte un peu de kérosène et d'entretien.
  final bool balls;

  /// Une étiquette propre à ce moment, à la place de celle de son genre.
  final String? tag;

  /// Année décimale (1974.83 = fin octobre 1974).
  final double year;
  final EventKind kind;
  final String date;
  final String city;
  final String title;
  final String text;

  /// Un moment de guerre : pas d'orages, mais des vagues d'avions de chasse (voir war_zones.dart).
  final bool war;

  /// Une éruption : on voit le volcan cracher sa lave sous l'avion.
  final bool volcano;

  /// La vignette d'archive (clé de archivePhotos) et la chanson du moment (clé de momentSongs).
  final String? photo;
  final String? song;

  /// Une seconde photo, qui alterne en fondu avec la première dans la fiche (le combat, après la poignée de main).
  final String? photo2;

  /// Un grand tournant (prise de pouvoir, changement de pays, passation) :
  /// le ciel entre en ébullition, le drapeau change sous tes yeux.
  final bool big;

  /// Le nom écrit sur la plaque du médaillon, à la place de l'année.
  final String? medal;

  /// Ce qu'il faut savoir en une ligne, annoncé avant que le médaillon arrive.
  final String? intro;

  int get yearLabel => year.floor();
}

